-- Run in DU_DOAN_SINH_VIEN after the base schema (existing and fresh installations).
SET XACT_ABORT ON;
BEGIN TRANSACTION;
IF OBJECT_ID('dbo.CK_TAI_KHOAN_VAI_TRO','C') IS NOT NULL
  ALTER TABLE dbo.TAI_KHOAN DROP CONSTRAINT CK_TAI_KHOAN_VAI_TRO;
ALTER TABLE dbo.TAI_KHOAN WITH CHECK ADD CONSTRAINT CK_TAI_KHOAN_VAI_TRO
  CHECK (VAI_TRO IN ('SINH_VIEN','GIANG_VIEN','ADMIN'));
IF OBJECT_ID('dbo.BO_DU_LIEU_TRAIN','U') IS NULL
  CREATE TABLE dbo.BO_DU_LIEU_TRAIN (
    ID_BO INT IDENTITY PRIMARY KEY, LOAI VARCHAR(20) NOT NULL,
    TEN_FILE NVARCHAR(150) NOT NULL, SO_DONG INT NOT NULL CHECK(SO_DONG>0),
    MA_BAM CHAR(64) NOT NULL, NOI_DUNG VARCHAR(MAX) NOT NULL,
    NGUOI_NHAP INT NOT NULL REFERENCES dbo.TAI_KHOAN(ID_TAI_KHOAN),
    NGAY_NHAP DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(), UNIQUE(LOAI,MA_BAM)
  );
IF COL_LENGTH('dbo.TAI_KHOAN','DA_XOA') IS NULL
  ALTER TABLE dbo.TAI_KHOAN ADD DA_XOA BIT NOT NULL CONSTRAINT DF_TAI_KHOAN_DA_XOA DEFAULT 0;
IF COL_LENGTH('dbo.GIANG_VIEN','KHOA') IS NULL
  ALTER TABLE dbo.GIANG_VIEN ADD KHOA NVARCHAR(100) NULL;
IF COL_LENGTH('dbo.GIANG_VIEN','NGANH') IS NULL
  ALTER TABLE dbo.GIANG_VIEN ADD NGANH NVARCHAR(100) NULL;
COMMIT;
